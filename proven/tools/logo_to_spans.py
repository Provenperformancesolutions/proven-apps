"""logo_to_spans.py <logo.png> <out logo-data.js>

Turns the Proven Performance Solutions logo (white lettering with light blue / dark blue / red details
on black) into horizontal colour spans, so the app can draw it sharp at any size and with a see-through
background on both render paths (the GPU renderer and the software fallback), with no image decoder
on the head unit.

  - crops to the artwork, classifies every pixel as background / white / light blue / dark blue / red
  - takes every STEP-th row, lists its runs of one colour, and merges neighbouring rows with the same runs
  - writes them as uint16 words (deflated, base64) with the line bands (PROVEN / PERFORMANCE / SOLUTIONS)

Words: nBands, then per band: y0, y1, nRuns, then per run: x0, x1, colour index (1..4). Units: pixels of the
cropped source, whose size is given as w, h.
"""
import base64, json, struct, sys, zlib
from PIL import Image

STEP = 2
PALETTE = {1: (255, 255, 255), 2: (80, 168, 224), 3: (8, 88, 152), 4: (224, 32, 40)}

def classify(r, g, b):
    mx, mn = max(r, g, b), min(r, g, b)
    if b - r > 40:                               # blues: half of the dark blue's own brightness is the edge
        if b < 76: return 0
        return 2 if (r - 80) ** 2 + (g - 168) ** 2 + (b - 224) ** 2 < (r - 8) ** 2 + (g - 88) ** 2 + (b - 152) ** 2 else 3
    if mx < 120: return 0
    return 4 if mx - mn > 90 and r > g + 60 else 1

def main(src, out):
    im = Image.open(src).convert('RGB')
    bbox = im.point(lambda v: 255 if v > 60 else 0).convert('L').getbbox()
    im = im.crop(bbox)
    W, H = im.size
    px = im.load()
    rows = []
    for y in range(0, H, STEP):
        yy = min(H - 1, y + STEP // 2)
        runs, cur, x0 = [], 0, 0
        for x in range(W):
            c = classify(*px[x, yy])
            if c != cur:
                if cur: runs.append((x0, x, cur))
                cur, x0 = c, x
        if cur: runs.append((x0, W, cur))
        rows.append((y, min(H, y + STEP), runs))
    bands = []
    for y0, y1, runs in rows:
        if bands and bands[-1][2] == runs and bands[-1][1] == y0: bands[-1][1] = y1
        else: bands.append([y0, y1, runs])
    bands = [b for b in bands if b[2]]
    # line bands: runs of rows with artwork, split at empty rows
    lines, cur = [], None
    for y0, y1, runs in rows:
        if runs:
            cur = [y0, y1] if cur is None else [cur[0], y1]
        elif cur is not None:
            lines.append(cur); cur = None
    if cur is not None: lines.append(cur)
    words = [len(bands)]
    for y0, y1, runs in bands:
        words += [y0, y1, len(runs)]
        for r in runs: words += list(r)
    raw = struct.pack('<%dH' % len(words), *words)
    b64 = base64.b64encode(zlib.compress(raw, 9)).decode('ascii')
    colors = ['#%02x%02x%02x' % PALETTE[i] for i in (1, 2, 3, 4)]
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write("'use strict';\n/** Proven Performance Solutions logo as colour spans. Generated by tools/logo_to_spans.py from the logo file: do not edit. */\n")
        f.write('module.exports = ' + json.dumps({'w': W, 'h': H, 'colors': colors, 'lines': lines, 'spans': b64}) + ';\n')
    print('cropped %dx%d, %d bands, %d runs, lines %s, %d bytes of data' % (W, H, len(bands), sum(len(b[2]) for b in bands), lines, len(b64)))

main(sys.argv[1], sys.argv[2])
